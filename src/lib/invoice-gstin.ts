/** PAN embedded in standard 15-char GSTIN (chars 3–12). */
export function panFromGstin(gstin: string | null | undefined): string | null {
  const g = gstin?.trim().toUpperCase();
  if (!g || g.length < 12) return null;
  return g.slice(2, 12);
}

